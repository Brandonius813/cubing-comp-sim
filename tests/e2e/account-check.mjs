import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import path from 'node:path';

/** Verifies provider entry points and that redirect return never auto-deletes. */
export async function checkAccountDialog(browser, origin, artifacts) {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
  const errors = [];
  const externalRequests = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => {
    if (new URL(request.url()).origin !== new URL(origin).origin) externalRequests.push(request.url());
  });
  const button = name => page.getByRole('button', { name, exact: true });
  const render = async (providers, callback, wcaId) => {
    const revision = await page.evaluate(([providers, callback, wcaId]) => window.accountFixture.render(providers, callback, wcaId), [providers, callback, wcaId]);
    await page.locator(`[data-account-fixture-revision="${revision}"]`).waitFor({ state: 'attached' });
    await page.getByRole('dialog', { name: 'Account & cloud save', exact: true }).waitFor();
  };
  const calls = () => page.evaluate(() => window.accountFixture.calls);
  try {
    await page.goto(`${origin}/tests/e2e/account.fixture.html`);
    await button('Continue with Google').waitFor();
    assert.equal(await page.evaluate(() => window.accountFixture.sdkConfigured), false, 'The UI-only fixture must not construct a live SDK client.');
    await page.evaluate(() => localStorage.setItem('account-ui-local-history-sentinel', 'kept'));
    await button('Continue with Google').click();
    assert.deepEqual(await calls(), [{ method: 'signInWithProvider', provider: 'google' }]);
    await render(null);
    await button('Continue with WCA').click();
    assert.deepEqual(await calls(), [{ method: 'signInWithProvider', provider: 'wca' }]);
    await render(null);
    await page.evaluate(() => window.accountFixture.failProvider());
    await button('Continue with Google').click();
    await page.getByRole('alert').waitFor();
    assert.match(await page.getByRole('alert').innerText(), /could not|failed/i);
    assert.equal(await button('Continue with WCA').isEnabled(), true, 'Provider failure must allow retry.');
    await render(['email']);
    await button('Connect WCA').click();
    assert.deepEqual(await calls(), [{ method: 'linkProvider', provider: 'wca' }]);
    await render(['google', 'custom:wca'], null, '2012TEST01');
    assert.equal(await page.getByRole('link', { name: 'WCA ID: 2012TEST01', exact: true }).getAttribute('href'), 'https://www.worldcubeassociation.org/persons/2012TEST01');
    await render(['custom:wca']);
    assert.equal(await page.locator('.wca-profile-link').count(), 0, 'WCA accounts without competitor IDs must not show a profile link.');
    assert.equal(await button('Connect WCA').count(), 0);
    assert.equal(await page.getByText('WCA connected', { exact: true }).count(), 1);
    await button('Delete account').click();
    await button('Confirm with WCA').click();
    assert.deepEqual(await calls(), [{ method: 'reauthenticateWithProvider', provider: 'wca' }]);
    await render(['google']);
    assert.equal(await button('Change password').count(), 0, 'OAuth-only users must not be asked to change a nonexistent password.');
    assert.equal(await button('Connect Google').count(), 0, 'Linked identities must not offer another connection.');
    assert.equal(await page.getByText('Google connected', { exact: true }).count(), 1);
    await button('Delete account').click();
    assert.equal(await page.getByLabel('Confirm your password', { exact: true }).count(), 0);
    assert.equal(await button('Permanently delete account').isEnabled(), false);
    await button('Confirm with Google').click();
    assert.deepEqual(await calls(), [{ method: 'reauthenticateWithProvider', provider: 'google' }]);
    await render(['google'], { purpose: 'delete', status: 'success', provider: 'google' });
    await button('Cancel').click();
    await button('Delete account').waitFor();
    assert.deepEqual(await calls(), [], 'Cancelling final deletion must preserve the account and history.');
    assert.equal(await page.evaluate(() => localStorage.getItem('account-ui-local-history-sentinel')), 'kept');
    await render(['google'], { purpose: 'delete', status: 'success', provider: 'google' });
    await page.getByLabel('Type your account email to confirm', { exact: true }).fill('solver@example.test');
    await page.evaluate(() => window.accountFixture.failProof());
    await button('Permanently delete account').click();
    await button('Confirm with Google').waitFor();
    assert.deepEqual(await calls(), [{ method: 'reauthenticatedDeletionSession' }], 'Expired proof must not request deletion.');
    assert.match(await page.getByRole('alert').innerText(), /Confirm your identity again/);
    for (const providers of [['google'], ['email']]) {
      await render(providers, providers[0] === 'google' ? { purpose: 'delete', status: 'success', provider: 'google' } : null);
      if (providers[0] === 'email') await button('Delete account').click();
      await page.getByLabel('Type your account email to confirm', { exact: true }).fill('solver@example.test');
      if (providers[0] === 'email') await page.getByLabel('Confirm your password', { exact: true }).fill('test-only-password');
      await page.evaluate(() => window.accountFixture.mismatch());
      await button('Permanently delete account').click();
      await page.getByRole('alert').waitFor();
      assert.equal((await calls()).some(call => call.method === 'deleteAccount'), false, 'An account switch must never delete the account shown in another tab.');
    }
    await render(['google'], { purpose: 'delete', status: 'success', provider: 'google' });
    await page.getByLabel('Type your account email to confirm', { exact: true }).waitFor();
    assert.deepEqual(await calls(), [], 'Returning from provider confirmation must not delete the account.');
    assert.equal(await button('Permanently delete account').isEnabled(), false);
    await page.getByLabel('Type your account email to confirm', { exact: true }).fill('wrong@example.test');
    assert.equal(await button('Permanently delete account').isEnabled(), false);
    await page.getByLabel('Type your account email to confirm', { exact: true }).fill('solver@example.test');
    await button('Permanently delete account').click();
    await page.getByText('Your account and cloud save were deleted. Times on this device are kept.', { exact: true }).waitFor();
    assert.deepEqual(await calls(), [{ method: 'reauthenticatedDeletionSession' }, { method: 'deleteAccount' }, { method: 'signOutAfterDeletion' }]);
    assert.equal(await page.evaluate(() => localStorage.getItem('account-ui-local-history-sentinel')), 'kept');
    await render(['email']);
    await button('Delete account').click();
    await page.getByLabel('Type your account email to confirm', { exact: true }).fill('solver@example.test');
    await page.getByLabel('Confirm your password', { exact: true }).fill('test-only-password');
    await button('Permanently delete account').click();
    await page.getByText('Your account and cloud save were deleted. Times on this device are kept.', { exact: true }).waitFor();
    assert.deepEqual(await calls(), [{ method: 'reauthenticateForDeletion' }, { method: 'deleteAccount' }, { method: 'signOutAfterDeletion' }]);
    await render(['google'], { purpose: 'link', status: 'error', provider: 'wca' });
    await page.getByRole('alert').waitFor();
    assert.deepEqual(await calls(), [], 'Failed callbacks must not transfer or delete history.');
    await render(null, { purpose: 'signin', status: 'error', reason: 'email_verification', provider: 'wca' });
    assert.match(await page.getByRole('alert').innerText(), /Check your email to verify/);
    await page.evaluate(() => window.accountFixture.withSave());
    for (const direction of ['Upload', 'Download']) {
      await render(['google']);
      await button(direction).waitFor();
      await button(direction).click();
      await page.evaluate(() => window.accountFixture.switchAuthUser());
      await button('Replace history').click();
      await page.getByRole('alert').waitFor();
      assert.deepEqual(await calls(), [], 'A changed account must be rejected before export, cloud transfer or local replacement.');
    }
    await render(['google']);
    await button('Download').click();
    await page.evaluate(() => window.accountFixture.switchDuringDownload());
    await button('Replace history').click();
    await page.getByRole('alert').waitFor();
    assert.deepEqual(await calls(), [{ method: 'downloadCloud' }], 'A changed account during download must never replace local history.');
    await render(['google']);
    await button('Upload').click();
    await page.evaluate(() => window.accountFixture.refreshToken());
    await button('Replace history').waitFor();
    await button('Replace history').click();
    await page.getByText('Cloud save replaced with this device’s history.', { exact: true }).waitFor();
    assert.deepEqual(await calls(), [{ method: 'exportHistory' }, { method: 'uploadCloud' }], 'Refreshing the same account token must preserve its upload confirmation.');
    await render(['google']);
    await button('Upload').click();
    await page.evaluate(() => window.accountFixture.switchDisplayedUser());
    await page.getByText('different@example.test', { exact: true }).waitFor();
    assert.equal(await button('Replace history').count(), 0, 'Changing displayed accounts must clear transfer confirmation.');
    await render(['google'], { purpose: 'delete', status: 'success', provider: 'google' });
    await page.getByLabel('Type your account email to confirm', { exact: true }).fill('solver@example.test');
    await page.evaluate(() => window.accountFixture.switchDisplayedUser());
    await page.getByText('different@example.test', { exact: true }).waitFor();
    assert.equal(await button('Permanently delete account').count(), 0, 'Changing displayed accounts must clear deletion confirmation and provider proof.');
    assert.deepEqual(await calls(), [{ method: 'recoveryComplete' }], 'Account switching must end the previous recovery context.');
    await render(['google'], { purpose: 'delete', status: 'success', provider: 'google' });
    await page.getByLabel('Type your account email to confirm', { exact: true }).fill('solver@example.test');
    await page.evaluate(() => window.accountFixture.holdDeletion());
    await button('Permanently delete account').click();
    await page.waitForFunction(() => window.accountFixture.deletionStarted());
    await page.evaluate(() => window.accountFixture.switchDisplayedUser());
    await page.getByText('different@example.test', { exact: true }).waitFor();
    await page.getByText('7 rounds · 0 solves', { exact: true }).waitFor();
    await page.evaluate(() => window.accountFixture.releaseDeletion());
    await page.waitForFunction(() => [...document.querySelectorAll('button')].some(button => button.textContent === 'Delete account' && !button.disabled));
    assert.equal(await page.getByText('Your account and cloud save were deleted. Times on this device are kept.', { exact: true }).count(), 0, 'A completed deletion for the previous account must not replace the new account summary.');
    assert.equal(await page.getByText('7 rounds · 0 solves', { exact: true }).count(), 1, 'The new account cloud metadata must remain visible.');
    assert.equal(await page.evaluate(() => localStorage.getItem('account-ui-local-history-sentinel')), 'kept');
    await render(['email']);
    await button('Delete account').click();
    await page.getByLabel('Type your account email to confirm', { exact: true }).fill('solver@example.test');
    await page.getByLabel('Confirm your password', { exact: true }).fill('test-only-password');
    await page.evaluate(() => window.accountFixture.holdPasswordReauth());
    await button('Permanently delete account').click();
    await page.waitForFunction(() => window.accountFixture.passwordReauthStarted());
    await page.evaluate(() => window.accountFixture.switchDisplayedUser());
    await page.getByText('different@example.test', { exact: true }).waitFor();
    await page.evaluate(() => window.accountFixture.releasePasswordReauth());
    await page.getByRole('alert').waitFor();
    assert.equal((await calls()).some(call => call.method === 'deleteAccount'), false, 'An account change during password confirmation must prevent deletion even when confirmation returns the old account token.');
    const recovery = async () => {
      const revision = await page.evaluate(() => window.accountFixture.renderRecovery());
      await page.locator(`[data-account-fixture-revision="${revision}"]`).waitFor({ state: 'attached' });
      await page.getByLabel('New password', { exact: true }).waitFor();
    };
    await recovery();
    await page.getByLabel('New password', { exact: true }).fill('test-only-new-password');
    await page.evaluate(() => window.accountFixture.switchAuthUser());
    await button('Update password').click();
    await page.getByRole('alert').waitFor();
    assert.deepEqual(await calls(), [{ method: 'updatePassword', userId: 'test-only-user' }], 'Password update must remain bound to the displayed recovery account.');
    await page.evaluate(() => window.accountFixture.switchDisplayedUser());
    await page.getByText('different@example.test', { exact: true }).waitFor();
    assert.equal(await page.getByLabel('New password', { exact: true }).count(), 0, 'An account change must discard the prior password form.');
    assert.deepEqual(await calls(), [{ method: 'updatePassword', userId: 'test-only-user' }, { method: 'recoveryComplete' }]);
    await recovery();
    await page.getByLabel('New password', { exact: true }).fill('test-only-new-password');
    await button('Update password').click();
    await page.getByText('Password updated.', { exact: true }).waitFor();
    assert.deepEqual(await calls(), [{ method: 'updatePassword', userId: 'test-only-user' }, { method: 'recoveryComplete' }], 'Successful recovery must end the recovery context.');
    await page.evaluate(() => window.accountFixture.providers(['google']));
    await render(null);
    assert.equal(await button('Continue with WCA').count(), 0, 'Unconfigured providers must be hidden.');
    await page.evaluate(() => window.accountFixture.providers(['google', 'wca']));
    await render(null);
    await page.evaluate(() => document.fonts.ready);
    const branding = await button('Continue with Google').evaluate(element => {
      const style = getComputedStyle(element);
      const logo = element.querySelector('img');
      return { background: style.backgroundColor, color: style.color, borderColor: style.borderColor, fontSize: style.fontSize, fontFamily: style.fontFamily, imageLoaded: logo.complete && logo.naturalWidth > 0, imageWidth: logo.width, imageHeight: logo.height };
    });
    assert.equal(branding.background, 'rgb(255, 255, 255)');
    assert.equal(branding.color, 'rgb(31, 31, 31)');
    assert.equal(branding.borderColor, 'rgb(116, 119, 117)');
    assert.equal(branding.fontSize, '14px');
    assert.match(branding.fontFamily, /CCS Google Sans/);
    assert.equal(branding.imageLoaded, true);
    assert.equal(branding.imageWidth, 18);
    assert.equal(branding.imageHeight, 18);
    const googleSize = await button('Continue with Google').boundingBox();
    const wcaSize = await button('Continue with WCA').boundingBox();
    assert.equal(googleSize.width, wcaSize.width);
    assert.equal(googleSize.height, wcaSize.height);
    await button('Continue with WCA').hover();
    assert.equal(await button('Continue with WCA').evaluate(element => getComputedStyle(element).backgroundColor), 'rgb(247, 247, 247)', 'Provider hover must preserve readable text contrast.');
    await page.mouse.move(1, 1);
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Account dialog overflows on mobile.');
    if (artifacts) { await mkdir(artifacts, { recursive: true }); await page.screenshot({ path: path.join(artifacts, 'account-mobile.png'), fullPage: true }); }
    assert.deepEqual(errors, []);
    assert.deepEqual(externalRequests, [], 'UI-only checks must not contact external auth or cloud services.');
    return 'Account provider sign-in, linking, password/provider deletion, callback safety, retries, configured providers and mobile layout passed.';
  } finally { await page.close(); }
}
